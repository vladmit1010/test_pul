SENTIMENT_WEIGHTS = {"positive": 42, "neutral": 33, "negative": 25}

START_DATE = datetime(2025, 1, 1)


def weighted_choice(items: dict) -> str:
    keys = list(items.keys())
    weights = [items[k]["weight"] if isinstance(items[k], dict) else items[k] for k in keys]
    return random.choices(keys, weights=weights, k=1)[0]


def generate_comment(comment_id: int) -> dict:
    persona = weighted_choice(PERSONAS)
    topic = weighted_choice(TOPICS)
    sentiment = random.choices(
        list(SENTIMENT_WEIGHTS.keys()),
        weights=list(SENTIMENT_WEIGHTS.values()),
        k=1,
    )[0]

    templates = TOPICS[topic]["templates"][sentiment]
    template = random.choice(templates)
    text = template.format(hours=random.randint(2, 48))

    author = random.choice(PERSONAS[persona]["names"])
    date = START_DATE + timedelta(days=random.randint(0, 220), hours=random.randint(8, 22))

    return {
        "id": comment_id,
        "author": author,
        "persona": persona,
        "topic": topic,
        "sentiment": sentiment,
        "text": text,
        "date": date.strftime("%Y-%m-%d %H:%M"),
    }


def build_summary(comments: list[dict]) -> dict:
    by_persona = {}
    by_topic = {}
    by_sentiment = {"positive": 0, "neutral": 0, "negative": 0}
    matrix = {}

    for c in comments:
        by_persona[c["persona"]] = by_persona.get(c["persona"], 0) + 1
        by_topic[c["topic"]] = by_topic.get(c["topic"], 0) + 1
        by_sentiment[c["sentiment"]] += 1
        key = f"{c['persona']}|{c['topic']}"
        matrix[key] = matrix.get(key, 0) + 1

    return {
        "total": len(comments),
        "byPersona": by_persona,
        "byTopic": by_topic,
        "bySentiment": by_sentiment,
        "matrix": matrix,
    }


def main() -> None:
    comments = [generate_comment(i + 1) for i in range(1000)]
    output = {
        "generatedAt": datetime.now().strftime("%Y-%m-%d %H:%M"),
        "summary": build_summary(comments),
        "comments": comments,
    }

    out_path = Path(__file__).resolve().parent.parent / "data" / "comments.json"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(output, f, ensure_ascii=False, indent=2)

    print(f"Сгенерировано {len(comments)} комментариев → {out_path}")


if __name__ == "__main__":
    main()
